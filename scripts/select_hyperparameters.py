"""Pick each algorithm's hyperparameters from the tuning runs and write configs/tuned.yaml.

Rule (identical for both algorithms): highest mean final V^pi(s0) over the
tuning seeds; ties (within 1e-3) broken by mean normalised AUC.
Also writes results/tables/tuning_summary.csv.
"""
from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

import yaml  # noqa: E402

from fxtd.analysis import load_experiment, per_seed_table  # noqa: E402
from fxtd.config import ROOT, load_config  # noqa: E402
from fxtd.mdp import TabularModel, make_env  # noqa: E402


def main() -> None:
    base = load_config("configs/base.yaml")
    model = TabularModel.from_env(make_env(base["env"]))
    v_star = model.value_iteration(base["gamma"])[0][0]
    df = per_seed_table(load_experiment("tuning"), v_star)
    summ = (df.groupby(["algo", "alpha", "eps_decay_fraction"], observed=True)
              .agg(mean_final_value=("final_value", "mean"), sd_final_value=("final_value", "std"),
                   mean_retained=("retained", "mean"), mean_auc=("auc", "mean"),
                   mean_success=("final_success", "mean"), n_seeds=("seed", "count"))
              .reset_index())
    out_tables = ROOT / "results" / "tables"; out_tables.mkdir(parents=True, exist_ok=True)
    summ.round(4).to_csv(out_tables / "tuning_summary.csv", index=False)

    chosen = {}
    for algo, g in summ.groupby("algo"):
        top = g["mean_final_value"].max()
        cands = g[g["mean_final_value"] >= top - 1e-3].sort_values("mean_auc", ascending=False)
        best = cands.iloc[0]
        chosen[algo] = {"alpha": float(best["alpha"]), "eps_decay_fraction": float(best["eps_decay_fraction"])}
        print(f"{algo}: alpha={best['alpha']}, eps_decay_fraction={best['eps_decay_fraction']}, "
              f"mean V={best['mean_final_value']:.4f} (retained {best['mean_retained']:.3f})")

    tuned = {"base": "base.yaml", "hyperparameters": chosen}
    with open(ROOT / "configs" / "tuned.yaml", "w", encoding="utf-8") as f:
        f.write("# GENERATED by scripts/select_hyperparameters.py from results/raw/tuning. Do not edit by hand.\n")
        yaml.safe_dump(tuned, f, sort_keys=False)
    print("wrote configs/tuned.yaml")


if __name__ == "__main__":
    main()
